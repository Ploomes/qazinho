/** What the preload exposes to the page as `window.qazinho`. Data and purposeful functions only. */
export interface IQazinhoApi {
  platform: Platform;
  detectAgents: () => Promise<IDetectedAgent[]>;
  readResources: () => Promise<IResourceSnapshot>;
  detectDeviceTools: () => Promise<IDeviceTools>;
  askAgent: (ask: IAskAgent) => Promise<IChatTurn>;
  stopAgent: (workspaceId: string) => Promise<void>;
  readAgentLimits: (agentId: string) => Promise<IAgentLimits | null>;
  onAgentEvent: (listener: (event: IAgentEvent) => void) => () => void;
  signInAgent: (agentId: string) => Promise<AgentSignInProgress>;
  cancelAgentSignIn: (agentId: string) => Promise<void>;
  sendAgentSignInCode: (props: { agentId: string; code: string }) => Promise<void>;
  onAgentSignIn: (listener: (progress: AgentSignInProgress) => void) => () => void;
  startRun: (run: IStartRun) => Promise<void>;
  pauseRun: (props: { workspaceId: string; isPaused: boolean }) => Promise<void>;
  stopRun: (workspaceId: string) => Promise<void>;
  resizeDevice: (props: { workspaceId: string; viewport: IViewport }) => Promise<void>;
  focusDevice: (props: { workspaceId: string; isFocused: boolean }) => Promise<void>;
  runsInFlight: () => Promise<IRunInFlight[]>;
  onRunEvent: (listener: (event: IRunEvent) => void) => () => void;
  replayUrl: (run: IRunRef) => Promise<string | null>;
  saveReplay: (props: IRunRef & { name: string }) => Promise<SaveOutcome>;
  alertRunEnded: (notice: IRunEndNotice) => void;
  onOpenRun: (listener: (run: IRunRef) => void) => () => void;
  readState: () => Promise<ISavedState>;
  saveProjects: (json: string) => Promise<void>;
  saveWorkspace: (saved: ISavedWorkspace) => Promise<void>;
  removeWorkspace: (workspaceId: string) => Promise<void>;
  readShot: (file: string) => Promise<string | null>;
  saveShot: (props: {
    file: string | null;
    src: string | null;
    name: string;
  }) => Promise<SaveOutcome>;
  pickFile: (kind: PickKind) => Promise<string | null>;
  fitWindow: (fit: WindowFit) => Promise<void>;
  checkMachine: () => Promise<IMachineCheck>;
  installTool: (item: InstallableId) => Promise<IInstallResult>;
  onSetupEvent: (listener: (event: ISetupEvent) => void) => () => void;
  listIntegrations: () => Promise<IIntegrationStatus[]>;
  connectIntegration: (connecting: IConnectIntegration) => Promise<IConnectResult>;
  disconnectIntegration: (id: IntegrationId) => Promise<void>;
  githubStatus: () => Promise<IGithubStatus>;
  signInGithub: () => Promise<GithubSignInProgress>;
  cancelGithubSignIn: () => Promise<void>;
  onGithubSignIn: (listener: (progress: GithubSignInProgress) => void) => () => void;
  listRepositories: () => Promise<IRepositoryList>;
  listBranches: (repository: IRepositoryRef) => Promise<IBranchList>;
  listMcpServers: (agentId: string) => Promise<IMcpServerStatus[]>;
  connectMcpServer: (signIn: IMcpSignIn) => Promise<McpSignInProgress>;
  cancelMcpSignIn: (target: IMcpServerTarget) => Promise<void>;
  onMcpSignIn: (listener: (progress: McpSignInProgress) => void) => () => void;
  removeMcpServer: (target: IMcpServerTarget) => Promise<McpActionResult>;
  askAssistant: (ask: IAssistantAsk) => Promise<IAssistantTurn>;
  stopAssistant: () => Promise<void>;
  onAssistantEvent: (listener: (event: IAgentEvent) => void) => () => void;
  onAppToolCall: (listener: (request: IAppToolRequest) => void) => () => void;
  answerAppTool: (answer: IAppToolAnswer) => void;
  startBuild: (build: IStartBuild) => Promise<IBuildResult>;
  stopBuild: (buildId: string) => Promise<void>;
  onBuildEvent: (listener: (event: IBuildEvent) => void) => () => void;
}
