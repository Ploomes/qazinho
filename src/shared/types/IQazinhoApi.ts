import type { IAgentEvent } from './IAgentEvent';
import type { IAskAgent } from './IAskAgent';
import type { IChatTurn } from './IChatTurn';
import type { IConnectIntegration } from './IConnectIntegration';
import type { IConnectResult } from './IConnectResult';
import type { IDetectedAgent } from './IDetectedAgent';
import type { IDeviceTools } from './IDeviceTools';
import type { IInstallResult } from './IInstallResult';
import type { IIntegrationStatus } from './IIntegrationStatus';
import type { IMachineCheck } from './IMachineCheck';
import type { IMcpServerStatus } from './IMcpServerStatus';
import type { IMcpServerTarget } from './IMcpServerTarget';
import type { InstallableId } from './InstallableId';
import type { IntegrationId } from './IntegrationId';
import type { IResourceSnapshot } from './IResourceSnapshot';
import type { IRunEvent } from './IRunEvent';
import type { IRunInFlight } from './IRunInFlight';
import type { IViewport } from './IViewport';
import type { ISavedState } from './ISavedState';
import type { ISavedWorkspace } from './ISavedWorkspace';
import type { ISetupEvent } from './ISetupEvent';
import type { IStartRun } from './IStartRun';
import type { McpActionResult } from './McpActionResult';
import type { McpSignInResult } from './McpSignInResult';
import type { PickKind } from './PickKind';
import type { Platform } from './Platform';

/** What the preload exposes to the page as `window.qazinho`. Data and purposeful functions only. */
export interface IQazinhoApi {
  platform: Platform;
  detectAgents: () => Promise<IDetectedAgent[]>;
  readResources: () => Promise<IResourceSnapshot>;
  detectDeviceTools: () => Promise<IDeviceTools>;
  askAgent: (ask: IAskAgent) => Promise<IChatTurn>;
  onAgentEvent: (listener: (event: IAgentEvent) => void) => () => void;
  startRun: (run: IStartRun) => Promise<void>;
  pauseRun: (props: { workspaceId: string; isPaused: boolean }) => Promise<void>;
  stopRun: (workspaceId: string) => Promise<void>;
  resizeDevice: (props: { workspaceId: string; viewport: IViewport }) => Promise<void>;
  runsInFlight: () => Promise<IRunInFlight[]>;
  onRunEvent: (listener: (event: IRunEvent) => void) => () => void;
  readState: () => Promise<ISavedState>;
  saveProjects: (json: string) => Promise<void>;
  saveWorkspace: (saved: ISavedWorkspace) => Promise<void>;
  removeWorkspace: (workspaceId: string) => Promise<void>;
  readShot: (file: string) => Promise<string | null>;
  pickFile: (kind: PickKind) => Promise<string | null>;
  checkMachine: () => Promise<IMachineCheck>;
  installTool: (item: InstallableId) => Promise<IInstallResult>;
  onSetupEvent: (listener: (event: ISetupEvent) => void) => () => void;
  listIntegrations: () => Promise<IIntegrationStatus[]>;
  connectIntegration: (connecting: IConnectIntegration) => Promise<IConnectResult>;
  disconnectIntegration: (id: IntegrationId) => Promise<void>;
  listMcpServers: (agentId: string) => Promise<IMcpServerStatus[]>;
  connectMcpServer: (target: IMcpServerTarget) => Promise<McpSignInResult>;
  removeMcpServer: (target: IMcpServerTarget) => Promise<McpActionResult>;
}
