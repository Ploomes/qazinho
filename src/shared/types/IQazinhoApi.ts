  downloadOrgProject: (props: {
    orgSlug: string;
    projectId: string;
  }) => Promise<ProDownload>;
  openProPage: (path: string) => Promise<boolean>;
  onProLink: (listener: () => void) => () => void;
  takeProLink: () => Promise<IProLink | null>;
  listRepositories: () => Promise<IRepositoryList>;
  listBranches: (repository: IRepositoryRef) => Promise<IBranchList>;
  searchJira: (query: string) => Promise<JiraIssueList>;
  listJiraProjects: () => Promise<JiraProjectList>;
  switchConfluence: (isOn: boolean) => Promise<ConfluenceSwitch>;
  searchConfluence: (query: string) => Promise<ConfluencePageList>;
  listConfluenceSpaces: () => Promise<ConfluenceSpaceList>;
  publishPlan: (plan: IPublishPlan) => Promise<PlanPublished>;
  fileBug: (request: IFileBug) => Promise<BugFiling>;
  onFilingEvent: (listener: (event: IFilingEvent) => void) => () => void;
  reviewBug: (request: IReviewBug) => Promise<BugReview>;
  commentBug: (request: ICommentBug) => Promise<BugComment>;
  listMcpServers: (agentId: string) => Promise<IMcpServerStatus[]>;
  connectMcpServer: (signIn: IMcpSignIn) => Promise<McpSignInProgress>;
  cancelMcpSignIn: (target: IMcpServerTarget) => Promise<void>;
  onMcpSignIn: (listener: (progress: McpSignInProgress) => void) => () => void;
  removeMcpServer: (target: IMcpServerTarget) => Promise<McpActionResult>;
